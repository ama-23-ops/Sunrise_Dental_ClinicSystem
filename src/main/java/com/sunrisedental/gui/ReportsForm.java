    private void btnGenerateDailyReportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateDailyReportActionPerformed
        // TODO add your handling code here:
        try {

        String dateText =
                txtReportDate
                        .getText()
                        .trim();

        if (dateText.isEmpty() ||
                dateText.equalsIgnoreCase("YYYY-MM-DD")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter a report date.",
                    "Report Error",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        // Validate date locally first.

        LocalDate reportDate =
                LocalDate.parse(dateText);


        // ==========================================
        // CALL REST API
        // ==========================================

        HttpResponse<String> response =
                reportApiClient
                        .getDailyAppointments(
                                reportDate.toString()
                        );


        // ==========================================
        // CHECK RESPONSE
        // ==========================================

        if (response.statusCode() != 200) {

            showApiError(
                    response,
                    "Report Error"
            );

            return;
        }


        // ==========================================
        // CONVERT JSON TO OBJECTS
        // ==========================================

        List<AppointmentDetails> appointments =
                objectMapper.readValue(
                        response.body(),
                        new TypeReference<
                                List<AppointmentDetails>
                        >() {}
                );


        // ==========================================
        // UPDATE TABLE
        // ==========================================

        DefaultTableModel model =
                (DefaultTableModel)
                tblReport.getModel();

        model.setRowCount(0);


        for (AppointmentDetails appointment
                : appointments) {

            model.addRow(new Object[]{

                appointment.appointmentNo,
                appointment.patientName,
                appointment.dentistName,
                appointment.treatmentName,
                appointment.appointmentDate,
                appointment.appointmentTime,
                appointment.status

            });
        }


        // ==========================================
        // NO RESULTS
        // ==========================================

        if (appointments.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "No appointments found for "
                    + reportDate,
                    "Daily Report",
                    JOptionPane.INFORMATION_MESSAGE
            );
        }

    } catch (
            java.time.format.DateTimeParseException e) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter date as YYYY-MM-DD.",
                "Report Error",
                JOptionPane.ERROR_MESSAGE
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Report Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnGenerateDailyReportActionPerformed

