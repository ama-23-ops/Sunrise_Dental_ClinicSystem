    private void selectUserRow(int userId) {

    DefaultTableModel model =
            (DefaultTableModel)
            tblUsers.getModel();

    for (int i = 0;
            i < model.getRowCount();
            i++) {

        int tableUserId =
                Integer.parseInt(
                        model.getValueAt(i, 0)
                        .toString()
                );

        if (tableUserId == userId) {

            tblUsers.setRowSelectionInterval(
                    i,
                    i
            );

            break;
        }
    }
}
    
