    private void btnSearchUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchUserActionPerformed
        // TODO add your handling code here:
        try {

        String username =
                txtSearchUsername
                .getText()
                .trim();

        if (username.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter a username to search."
            );

            return;
        }

        User user =
                userService.findByUsername(
                        username
                );

        if (user == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "User not found."
            );

            return;
        }

        txtUserId.setText(
                String.valueOf(
                        user.getUserId()
                )
        );

        txtUsername.setText(
                user.getUsername()
        );

        txtFullName.setText(
                user.getFullName()
        );

        cmbRole.setSelectedItem(
                user.getRole()
        );

        // Never display the stored password
        txtPassword.setText("");

        txtConfirmPassword.setText("");

        selectUserRow(
                user.getUserId()
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Search Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnSearchUserActionPerformed

    private void btnUpdateUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateUserActionPerformed
        // TODO add your handling code here:
        try {

        String userIdText =
                txtUserId.getText().trim();

        if (userIdText.isEmpty()) {

            throw new IllegalArgumentException(
                    "Please search and select a user first."
            );
        }

        int userId =
                Integer.parseInt(userIdText);

        String username =
                txtUsername.getText().trim();

        String fullName =
                txtFullName.getText().trim();

        String password =
                new String(
                        txtPassword.getPassword()
                );

        String confirmPassword =
                new String(
                        txtConfirmPassword.getPassword()
                );

        String role =
                cmbRole.getSelectedItem()
                        .toString();

        // Validate username
        if (username.isEmpty()) {

            throw new IllegalArgumentException(
                    "Please enter a username."
            );
        }

        // Validate full name
        if (fullName.isEmpty()) {

            throw new IllegalArgumentException(
                    "Please enter the full name."
            );
        }

        // Check username conflict
        User existingUser =
                userService.findByUsername(username);

        if (existingUser != null
                && existingUser.getUserId()
                != userId) {

            throw new IllegalArgumentException(
                    "Username already exists."
            );
        }

        // Create User object
        User user = new User();

        user.setUserId(userId);

        user.setUsername(username);

        user.setFullName(fullName);

        user.setRole(role);

        /*
         * If password fields are empty:
         * keep the existing password.
         *
         * If a new password is entered:
         * hash it before saving.
         */
        boolean changePassword =
                !password.isEmpty();

        if (changePassword) {

            if (!password.equals(
                    confirmPassword)) {

                throw new IllegalArgumentException(
                        "Passwords do not match."
                );
            }

            // IMPORTANT:
            // Hash new password
            user.setPassword(
                    PasswordUtil.hashPassword(
                            password
                    )
            );
        }

        // Update user
        userService.update(
                user,
                changePassword
        );

        // Refresh table
        loadUsers();

        // Keep selected user
        selectUserRow(userId);

        // Clear password fields
        txtPassword.setText("");
        txtConfirmPassword.setText("");

        JOptionPane.showMessageDialog(
                this,
                "User updated successfully."
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "User Update Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnUpdateUserActionPerformed

