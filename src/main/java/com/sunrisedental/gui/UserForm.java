    private void loadUsers() {

    try {

        List<User> users =
                userService.findAll();

        DefaultTableModel model =
                (DefaultTableModel)
                tblUsers.getModel();

        model.setRowCount(0);

        for (User user : users) {

            model.addRow(
                    new Object[]{

                        user.getUserId(),
                        user.getUsername(),
                        user.getFullName(),
                        user.getRole()

                    }
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error loading users: "
                + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

