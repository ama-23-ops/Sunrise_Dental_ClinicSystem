    private void btnSaveUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveUserActionPerformed
        // TODO add your handling code here:
        try {

        String username =
                txtUsername.getText().trim();

        String fullName =
                txtFullName.getText().trim();

        String password =
                new String(
                        txtPassword.getPassword()
                );

        String confirmPassword =
                new String(
                        txtConfirmPassword.getPassword()
                );

        String role =
                cmbRole.getSelectedItem()
                        .toString();

        // Validate username
        if (username.isEmpty()) {

            throw new IllegalArgumentException(
                    "Please enter a username."
            );
        }

        // Validate full name
        if (fullName.isEmpty()) {

            throw new IllegalArgumentException(
                    "Please enter the full name."
            );
        }

        // Validate password
        if (password.isEmpty()) {

            throw new IllegalArgumentException(
                    "Please enter a password."
            );
        }

        // Confirm password
        if (!password.equals(confirmPassword)) {

            throw new IllegalArgumentException(
                    "Passwords do not match."
            );
        }

        // Check whether username already exists
        User existingUser =
                userService.findByUsername(username);

        if (existingUser != null) {

            throw new IllegalArgumentException(
                    "Username already exists."
            );
        }

        // Create User
        User user = new User();

        user.setUsername(username);

        user.setFullName(fullName);

        user.setRole(role);
        
        // Hash the password before saving
        user.setPassword(
                PasswordUtil.hashPassword(password)
        );

        // Save user
        userService.create(user);

        // Refresh table
        loadUsers();

        // Clear form
        clearUserForm();

        JOptionPane.showMessageDialog(
                this,
                "User created successfully."
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "User Registration Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnSaveUserActionPerformed

    private void btnDeleteUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteUserActionPerformed
        // TODO add your handling code here:
        try {

        // Check whether a user has been selected
        String userIdText =
                txtUserId.getText().trim();

        if (userIdText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please search and select a user first.",
                    "Delete User",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        int userId =
                Integer.parseInt(userIdText);

        // Prevent the currently logged-in user
        // from deleting their own account
        if (currentUser != null
                && userId == currentUser.getUserId()) {

            JOptionPane.showMessageDialog(
                    this,
                    "You cannot delete your own "
                    + "currently logged-in account.",
                    "Delete User",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        // Ask for confirmation
        int choice =
                JOptionPane.showConfirmDialog(
                        this,
                        "Are you sure you want to delete "
                        + "this user?",
                        "Confirm Delete",
                        JOptionPane.YES_NO_OPTION,
                        JOptionPane.WARNING_MESSAGE
                );

        if (choice != JOptionPane.YES_OPTION) {
            return;
        }

        // Delete user from database
        userService.delete(userId);

        // Refresh table
        loadUsers();

        // Clear the form
        clearUserForm();

        JOptionPane.showMessageDialog(
                this,
                "User deleted successfully.",
                "Delete User",
                JOptionPane.INFORMATION_MESSAGE
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Invalid user ID.",
                "Delete Error",
                JOptionPane.ERROR_MESSAGE
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error deleting user: "
                + e.getMessage(),
                "Delete Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnDeleteUserActionPerformed

